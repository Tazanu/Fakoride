/**
 * Copy the Terms and the Privacy policy from the app into the API.
 *
 *   npm run legal:sync
 *
 * The words are written once, in apps/mobile/src/content, because the app is
 * where people agree to them. But a store listing needs the privacy policy at
 * a web address, and somebody who has uninstalled the app needs to be able to
 * read how to delete their account — so the API serves the same words as plain
 * pages (see src/modules/public-pages.ts).
 *
 * The API is built from its own folder and cannot reach into the app's, so it
 * keeps a copy: src/content/legal.ts, written by this script and committed.
 * tests/legal-copy.test.ts fails when the copy and the original differ, which
 * is what stops the page a regulator reads from saying something the app does
 * not.
 *
 * A .mjs on purpose: the typecheck does not follow it into the app's folder,
 * whose imports only resolve inside the app.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { TERMS } = await import("../../apps/mobile/src/content/terms.ts");
const { PRIVACY } = await import("../../apps/mobile/src/content/privacy.ts");

const out = `/**
 * GENERATED by scripts/sync-legal.mjs — do not edit.
 *
 * The originals are apps/mobile/src/content/terms.ts and privacy.ts. Change
 * them there, then run \`npm run legal:sync\`. A test fails if the two differ.
 */

export type LegalSection = { heading: string; body: string[] };
export type LegalText = { title: string; updated: string; intro: string; sections: LegalSection[]; footer: string };
export type LegalDocument = { en: LegalText; fr: LegalText };

export const LEGAL: { terms: LegalDocument; privacy: LegalDocument } = ${JSON.stringify({ terms: TERMS, privacy: PRIVACY }, null, 2)};
`;

writeFileSync(join(here, "../src/content/legal.ts"), out);
console.log("Wrote src/content/legal.ts");
